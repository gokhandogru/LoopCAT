if (require.main === module) {
  const fs = require("node:fs");
  const path = require("node:path");
  const crypto = require("node:crypto");
  const root = path.resolve(__dirname, "..");
  const sourcePath = path.join(root, "i18n/source.en-US.json");
  const source = JSON.parse(fs.readFileSync(sourcePath, "utf8"));
  const locales = ["en-US", "tr-TR", "es-ES", "ca-ES", "ar"];
  const catalogs = locales.map((locale) => JSON.parse(fs.readFileSync(path.join(root, `i18n/locales/${locale}.json`), "utf8")));
  for (const row of rows.split("\n")) {
    const translations = row.split("|");
    const message = translations[0];
    const existing = Object.entries(source.messages).find(([, entry]) => (entry.message || entry) === message);
    const key = existing?.[0] || `subtitle.${crypto.createHash("sha1").update(message).digest("hex").slice(0, 8)}`;
    source.messages[key] ||= { message, description: "Subtitle editing", locations: ["src/features/editor/subtitle-controller.js"] };
    catalogs.forEach((catalog, index) => { catalog.messages[key] = translations[index]; });
  }
  fs.writeFileSync(sourcePath, JSON.stringify(source, null, 2) + "\n");
  catalogs.forEach((catalog, index) => fs.writeFileSync(path.join(root, `i18n/locales/${locales[index]}.json`), JSON.stringify(catalog, null, 2) + "\n"));
}
